function usage() {
  console.error('usage: node tools/map2json.js <scenario.SCN | folder> [...] [--out DIR] [--rooms] [--images] [--pretty]');
  console.error('  --rooms   from a folder, convert only the maps of the default ROOMS (src/config.js)');
  process.exit(2);
}

/** The base names of the server's default rooms (`ROOMS` in src/config.js), upper case, without extension. */
export function defaultRoomBases() {
  return String(DEFAULTS.ROOMS).split(',').map((s) => s.trim().split(':')[0].toUpperCase().replace(/\.SCN$/, '')).filter(Boolean);
}

export function main(argv) {
  const inputs = [];
  let outDir = null;
  let images = false;
  let pretty = false;
  let roomsOnly = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--out') outDir = argv[++i];
    else if (a === '--images') images = true;
    else if (a === '--pretty') pretty = true;
    else if (a === '--rooms') roomsOnly = true;
    else if (a.startsWith('--')) usage();
    else inputs.push(a);
  }
  if (inputs.length === 0) usage();

  const rooms = defaultRoomBases();
  const scnFiles = [];
  for (const inp of inputs) {
    const st = fs.statSync(inp);
    if (st.isDirectory()) {
      for (const e of fs.readdirSync(inp).sort()) {
        if (!/\.scn$/i.test(e)) continue;
        if (roomsOnly && !rooms.includes(e.replace(/\.scn$/i, '').toUpperCase())) continue;
        scnFiles.push(path.join(inp, e));
      }
    } else {
      scnFiles.push(inp);
    }
  }
  if (roomsOnly) {
    const found = scnFiles.map((f) => path.basename(f).replace(/\.scn$/i, '').toUpperCase());
    for (const r of rooms) if (!found.includes(r)) console.error(`warning: room map ${r}.SCN not found in the given folder(s)`);
  }
  if (scnFiles.length === 0) { console.error('no .SCN files found'); process.exit(1); }
  if (scnFiles.length > 1 && !outDir) { console.error('several scenarios: --out DIR is required'); process.exit(1); }

  const index = [];
  let failed = 0;
  for (const scn of scnFiles) {
    let data;
    try {
      data = convertScenario(scn, { images });
    } catch (e) {
      failed++;
      console.error(`${scn}: ${e.message}`);
      continue;
    }
    const text = pretty ? JSON.stringify(data, null, 2) : stringifyCompact(data);
    if (outDir) {
      fs.mkdirSync(outDir, { recursive: true });
      const file = `${data.source.base.toUpperCase()}.json`;
      fs.writeFileSync(path.join(outDir, file), text + '\n');
      index.push({
        file: data.source.files.scn.toUpperCase(), json: file, name: data.name, terrain: data.terrain,
        players: data.players, width: data.width, height: data.height, teams: data.teams.filter((t) => t.active).length,
      });
      console.error(`${file}: ${data.name} (${data.terrain}, ${data.width}x${data.height}, ${text.length} bytes)`);
    } else {
      process.stdout.write(text + '\n');
    }
  }
  if (outDir && index.length) {
    fs.writeFileSync(path.join(outDir, 'index.json'), stringifyCompact({ format: FORMAT, version: FORMAT_VERSION, maps: index }) + '\n');
  }
  if (failed) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
