// ---------------------------------------------------------------------------------------------
// Binary files

/** .MAP: u32 width, u32 height, width*height x {u16 background, u16 foreground}, width*height x u16 attributes. */
export function parseMap(buf) {
  if (buf.length < 8) throw new Error('.MAP too short');
  const width = buf.readUInt32LE(0);
  const height = buf.readUInt32LE(4);
  if (width < 1 || width > MAX_MAP_SIDE || height < 1 || height > MAX_MAP_SIDE) {
    throw new Error(`.MAP size ${width}x${height} out of range 1..256`);
  }
  const n = width * height;
  if (buf.length !== 8 + 6 * n) throw new Error(`.MAP length ${buf.length}, expected ${8 + 6 * n} for ${width}x${height}`);
  const background = [];
  const foreground = [];
  const attributes = [];
  for (let z = 0; z < height; z++) {
    const r = height - 1 - z; // file row -> game z
    const bg = new Array(width);
    const fg = new Array(width);
    const at = new Array(width);
    for (let x = 0; x < width; x++) {
      const i = r * width + x;
      bg[x] = buf.readUInt16LE(8 + i * 4);
      fg[x] = buf.readUInt16LE(8 + i * 4 + 2);
      at[x] = buf.readUInt16LE(8 + 4 * n + i * 2);
    }
    background.push(bg);
    foreground.push(fg);
    attributes.push(at);
  }
  return { width, height, background, foreground, attributes };
}

/** .MTG: u8 width, u8 height, width*height x u8 trigger id (bits 6 and 7 must be clear). */
export function parseMtg(buf, width, height) {
  if (buf.length !== 2 + width * height) throw new Error(`.MTG length ${buf.length}, expected ${2 + width * height}`);
  if (buf[0] !== (width & 0xff) || buf[1] !== (height & 0xff)) {
    throw new Error(`.MTG header ${buf[0]}x${buf[1]} does not match the .MAP ${width}x${height}`);
  }
  const grid = [];
  let maxTrigger = 0;
  for (let z = 0; z < height; z++) {
    const r = height - 1 - z;
    const row = new Array(width);
    for (let x = 0; x < width; x++) {
      const v = buf[2 + r * width + x];
      if (v & 0xc0) throw new Error(`.MTG trigger ${v} at x=${x} z=${z} has bits 6/7 set`);
      row[x] = v;
      if (v > maxTrigger) maxTrigger = v;
    }
    grid.push(row);
  }
  return { grid, maxTrigger };
}

/** .PTH: 65536 bytes next[a][b] (family routing matrix), then width*height x u8 family (0 = impassable), rows in game z order. */
export function parsePth(buf, width, height) {
  if (buf.length !== 65536 + width * height) throw new Error(`.PTH length ${buf.length}, expected ${65536 + width * height}`);
  const families = [];
  let maxFamily = 0;
  for (let z = 0; z < height; z++) {
    const row = new Array(width);
    for (let x = 0; x < width; x++) {
      const v = buf[65536 + z * width + x];
      row[x] = v;
      if (v > maxFamily) maxFamily = v;
    }
    families.push(row);
  }
  // The 256x256 routing matrix stays a byte table (base64): next[a][b] = byte a*256+b. As nested
  // JSON arrays it was more than half of every file.
  return { families, maxFamily, next: buf.subarray(0, 65536).toString('base64') };
}

/** Decode the base64 routing matrix of the JSON back into a lookup: routing(a, b) -> next family (0 = unreachable). */
export function routingTable(nextBase64) {
  const m = Buffer.from(nextBase64, 'base64');
  if (m.length !== 65536) throw new Error(`routing matrix has ${m.length} bytes, expected 65536`);
  return (a, b) => m[a * 256 + b];
}

/** .OVH / .O16: two 96x84 planes (day, night), 8 bpp in .OVH, 16 bpp in .O16. Kept as base64. */
export function parseOverview(buf, bytesPerPixel) {
  const planeBytes = OVERVIEW.width * OVERVIEW.height * bytesPerPixel;
  const expected = planeBytes * OVERVIEW.planes;
  return {
    width: OVERVIEW.width,
    height: OVERVIEW.height,
    bytesPerPixel,
    planes: ['day', 'night'],
    trailingBytes: buf.length - expected,
    data: buf.subarray(0, expected).toString('base64'),
  };
}

