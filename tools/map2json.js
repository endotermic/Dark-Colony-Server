// Scenario = the set of files

const EXTS = ['scn', 'map', 'mtg', 'pth', 'tro', 'pop', 'ovh', 'o16'];

/** Case-insensitive lookup of `<base>.<ext>` in `dir`; DOS-era folders mix upper and lower case. */
export function findScenarioFiles(dir, base) {
  const entries = fs.readdirSync(dir);
  const found = {};
  for (const e of entries) {
    const dot = e.lastIndexOf('.');
    if (dot < 0) continue;
    const stem = e.slice(0, dot);
    const ext = e.slice(dot + 1).toLowerCase();
    if (stem.toLowerCase() === base.toLowerCase() && EXTS.includes(ext) && !(ext in found)) found[ext] = e;
  }
  return found;
}

/**
 * Convert one scenario. `scnPath` is the .SCN file (any case); the sibling files are found by base
 * name. Options: { images: false } to include the .OVH/.O16 caches.
 */
export function convertScenario(scnPath, opts = {}) {
  const dir = path.dirname(scnPath);
  const base = path.basename(scnPath).replace(/\.[^.]*$/, '');
  const files = findScenarioFiles(dir, base);
  if (!files.scn) throw new Error(`no .SCN for ${base} in ${dir}`);
  if (!files.map) throw new Error(`no .MAP for ${base} in ${dir}`);
  const read = (ext) => fs.readFileSync(path.join(dir, files[ext]));

  const scn = parseScn(read('scn').toString('latin1'));
  const map = parseMap(read('map'));
  const mtg = files.mtg ? parseMtg(read('mtg'), map.width, map.height) : null;
  const pth = files.pth ? parsePth(read('pth'), map.width, map.height) : null;
  const triggers = files.tro ? parseTro(read('tro').toString('latin1')) : [];
  const pop = files.pop ? parsePop(read('pop').toString('latin1')) : null;

  const out = {
    format: FORMAT,
    version: FORMAT_VERSION,
    source: { dir: path.resolve(dir), base, files },
    name: scn.name,
    terrainFile: scn.terrainFile,
    terrain: scn.terrainFile.replace(/\.bts$/i, '').toLowerCase(),
    baseName: scn.baseName,
    players: playersFromFileName(files.scn),
    width: map.width,
    height: map.height,
    header: scn.header,
    teams: scn.teams,
    objects: scn.objects,
    tiles: {
      // Tile numbers are the editor's ("original") indices, < remapCount of the terrain's .BTS, which the
      // game remaps to its tile-bank slots on load (docs/DC16_MAP_FILES.md §3.1). 0 = no foreground tile.
      background: map.background,
      foreground: map.foreground,
      // attribute word per cell: bit 9 blocking, bits 0-3 foreground level (cleared without a foreground
      // tile), bits 10-15 terrain class; see the document for the rest
      attributes: map.attributes,
    },
    triggerIds: mtg ? mtg.grid : null,
    // families[z][x]: connected walkable region id, 0 = impassable; next: base64 of the 65536-byte
    // matrix next[a][b] (tools/map2json.js routingTable() decodes it)
    path: pth ? { families: pth.families, maxFamily: pth.maxFamily, next: pth.next } : null,
    script: triggers,
    eruptions: pop,
  };
  if (opts.images) {
    out.overview = {
      ovh: files.ovh ? parseOverview(read('ovh'), 1) : null,
      o16: files.o16 ? parseOverview(read('o16'), 2) : null,
    };
  }
  return out;
}

/** Multiplayer file names carry the player count in the 2nd character (`D8PLAY01.SCN` = 8); null otherwise. */
export function playersFromFileName(file) {
  const c = file[1];
  return c >= '1' && c <= '8' && /^[A-Za-z]\d/.test(file) ? Number(c) : null;
}

/** Compact JSON: objects one key per line, arrays of numbers on one line, grids one row per line. */
export function stringifyCompact(value, indent = 0) {
  const pad = '  '.repeat(indent);
  const pad1 = '  '.repeat(indent + 1);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    if (value.every((v) => typeof v === 'number' || v === null || typeof v === 'boolean')) return `[${value.join(',')}]`;
    return `[\n${value.map((v) => pad1 + stringifyCompact(v, indent + 1)).join(',\n')}\n${pad}]`;
  }
  if (value !== null && typeof value === 'object') {
    const keys = Object.keys(value);
    if (keys.length === 0) return '{}';
    return `{\n${keys.map((k) => `${pad1}${JSON.stringify(k)}: ${stringifyCompact(value[k], indent + 1)}`).join(',\n')}\n${pad}}`;
  }
  return JSON.stringify(value);
}

