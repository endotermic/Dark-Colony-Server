// Text files

const NUM = /^-?\d+$/;

function splitLines(text) {
  return text.split('\n').map((l) => l.replace(/\r$/, ''));
}

/** The game's scenario line reader (mobiles.c 0x41BA3C): skips empty lines and '%' comment lines. */
class ScnReader {
  constructor(text) {
    this.lines = splitLines(text);
    this.pos = 0;
  }
  next(what) {
    while (this.pos < this.lines.length) {
      const l = this.lines[this.pos++];
      if (l.length === 0 || l[0] === '%') continue;
      return l;
    }
    if (what) throw new Error(`.SCN ended before ${what} (line ${this.pos})`);
    return null;
  }
  ints(what) {
    const l = this.next(what);
    return l.trim().split(/\s+/).filter((t) => t.length).map((t) => (NUM.test(t) ? Number(t) : t));
  }
}

const TEAM_COUNT = 8;
const BUILDING_ROWS = 8;
const CITY_SLOT_PAIRS = 5;

/** .SCN: three name lines, five header lines, eight TEAM blocks, then object lines until EOF. */
export function parseScn(text) {
  const rd = new ScnReader(text);
  const terrainFile = rd.next('terrain file').trim();
  const baseName = rd.next('base name').trim();
  const name = rd.next('scenario name').trim();
  const h4 = rd.ints('header line 4');
  const startPhase = Number(rd.next('start phase'));
  const phaseLength = Number(rd.next('phase length'));
  const phaseCounter = Number(rd.next('phase counter'));
  const dawnLength = Number(rd.next('dawn length'));
  const header = {
    scenarioType: h4[0] ?? null, // ignored by the game (mobiles.c reads and drops the line); 0 = multiplayer maps, 1/12 = campaign
    teamCount: h4[1] ?? null,    // ignored by the game; equals the number of TEAM blocks with the active flag set
    startPhase,   // gs+0x53C: 0 day, 1 night
    phaseLength,  // gs+0x534: ticks of one day or night phase
    phaseCounter, // gs+0x530: phase counter at start
    dawnLength,   // gs+0x538: ticks of the dawn / dusk fade
  };

  const teams = [];
  for (let i = 0; i < TEAM_COUNT; i++) {
    const t = rd.ints(`TEAM ${i}`);
    if (t[0] !== 'TEAM' || t[1] !== i) throw new Error(`expected "TEAM ${i}", got "${t.join(' ')}"`);
    const race = Number(rd.next('%Race'));
    const money = Number(rd.next('%Money'));
    const ai = Number(rd.next('%AI'));
    const colour = Number(rd.next('%TeamColour'));
    const depend = rd.ints('%Depend').filter((v) => typeof v === 'number');
    const allies = rd.ints('%TeamAllies').filter((v) => typeof v === 'number');
    const aiSlots = rd.ints('%AISlots').filter((v) => typeof v === 'number');
    const start = rd.ints('city start position');
    const city = rd.ints('city origin');
    const slots = rd.ints('city slots').filter((v) => typeof v === 'number');
    const citySlots = [];
    for (let k = 0; k < CITY_SLOT_PAIRS && 2 * k + 1 < slots.length; k++) citySlots.push({ type: slots[2 * k], count: slots[2 * k + 1] });
    const buildings = [];
    for (let j = 0; j < BUILDING_ROWS; j++) {
      const row = rd.ints(`building row ${j} of team ${i}`).filter((v) => typeof v === 'number');
      buildings.push({ raw: row, weaponLevel: row[2] ?? 0, armourLevel: row[3] ?? 0 });
    }
    teams.push({
      index: i,
      active: t[2] === 1,                       // 3rd number of the TEAM line; written by the editor, not read by the game
      race,                                     // 0 human, 1 gray (campaign only; lobby value in multiplayer)
      money,
      ai,                                       // 0 human, 1..4 AI personality (campaign only)
      colour,                                   // -1 = team index (campaign only)
      depend: stripTerminator(depend),          // DEPEND items already researched (indices < 110), -1 terminated
      allies: allies.slice(0, TEAM_COUNT),      // 8 flags (the game reads the first 8 of the 16 numbers)
      aiSlots: stripTerminator(aiSlots),        // the line under %AISlots; read and ignored by the game
      start: { x: start[0], z: start[1] },     // player+0x38/+0x3C: start position (commander, initial view); (0,0) = same as city
      city: { x: city[0], z: city[1] },        // player+0x30/+0x34: city origin; (0,0) = team has no city
      citySlots,                                // 5 (type,count) pairs, count -1 = unused (all shipped maps)
      buildings,                                // 8 rows, one per building of the race's list: [2] weapon level, [3] armour level
    });
  }

  const objects = [];
  for (;;) {
    const l = rd.next();
    if (l === null) break;
    const v = l.trim().split(/\s+/).filter((t) => t.length && NUM.test(t)).map(Number);
    if (v.length < 5) continue; // sscanf("%d %d %d %d %d %d") with fewer fields; such lines do not occur
    objects.push(decodeObject(v));
  }

  return { terrainFile, baseName, name, header, teams, objects };
}

function stripTerminator(a) {
  const i = a.indexOf(-1);
  return i < 0 ? a : a.slice(0, i);
}

/** One `x z type player a b` line of the .SCN object list (b defaults to 0), decoded as mobiles.c 0x41C603 does. */
export function decodeObject(v) {
  const [x, z, type, player, a, b = 0] = v;
  const o = { x, z, type, typeName: TYPE_NAMES[type] ?? null, player, a, b };
  if (player === -1) {
    o.role = 'spawner'; // renat.c 0x43FFB0: table of at most 25 entries, `a` < 10 (creature generators)
  } else if (type === TYPE_VENT) {
    o.role = 'vent';
    o.rate = player;   // the 4th column is the vent's rate (0 = dormant until a trigger erupts it)
    o.money = a;       // the 5th column is the petra amount
  } else if (type === TYPE_ARTIFACT_SITE) {
    o.role = 'artifactSite';
  } else {
    o.role = 'unit';
  }
  return o;
}

/** .POP (map editor only): four eruption timing values, then `x z 40 rate money` lines of the erupting vents. */
export function parsePop(text) {
  const lines = splitLines(text).map((l) => l.trim()).filter((l) => l.length && l[0] !== '%');
  const timing = [];
  const vents = [];
  for (const l of lines) {
    const v = l.split(/\s+/).filter((t) => NUM.test(t)).map(Number);
    if (v.length === 1 && timing.length < 4 && vents.length === 0) timing.push(v[0]);
    else if (v.length >= 5) vents.push({ x: v[0], z: v[1], type: v[2], rate: v[3], money: v[4] });
  }
  return { timing, vents };
}

const TRO_HEADER = /^(\d+)\s+(norm|trip)\b\s*(.*)$/i;

/** .TRO (renat.c 0x43FD1C): blocks `<id> norm|trip [flag] <condition>` + action lines + `end`. */
export function parseTro(text) {
  const triggers = [];
  let cur = null;
  const lines = splitLines(text);
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i].trim();
    if (!l) continue;
    if (cur === null) {
      const m = TRO_HEADER.exec(l);
      if (!m) throw new Error(`.TRO line ${i + 1}: expected a trigger header, got "${l}"`);
      let rest = m[3].trim();
      let flag = null;
      const f = /^(-?\d+)\s*(.*)$/.exec(rest);
      if (f) { flag = Number(f[1]); rest = f[2]; }
      cur = { id: Number(m[1]), type: m[2].toLowerCase(), flag, condition: rest, actions: [] };
      continue;
    }
    if (l.toLowerCase() === 'end') { triggers.push(cur); cur = null; continue; }
    const parts = l.split(/\s+/);
    const op = parts[0].toLowerCase();
    const args = parts.slice(1).map((t) => (NUM.test(t) ? Number(t) : t));
    // expression arguments such as `setarray 0 (c+45)` may contain spaces: re-join everything after the numbers
    const firstExpr = args.findIndex((t) => typeof t === 'string');
    if (firstExpr >= 0) {
      const expr = parts.slice(1 + firstExpr).join(' ');
      args.splice(firstExpr, args.length - firstExpr, expr);
    }
    cur.actions.push({ op, args });
  }
  if (cur) { cur.unterminated = true; triggers.push(cur); }
  return triggers;
}

