// Dark Colony scenario ("map") files -> JSON. Library + CLI, no dependencies.
//
//   node tools/map2json.js <dir-or-.SCN> [...] [--out DIR] [--rooms] [--images] [--pretty]
//
//   node tools/map2json.js "../Dark-Colony/DC - Classic/SCENARIO/MPLAYER" --rooms --out maps
//       the seven maps of the server's default ROOMS (src/config.js) -> maps/<BASE>.json + maps/index.json
//   node tools/map2json.js "../Dark-Colony/DC - Classic/SCENARIO/MPLAYER" --out some/dir
//       every scenario of the folder (not kept in the repository; generate on request)
//   node tools/map2json.js "../Dark-Colony/DC - Classic/SCENARIO/MPLAYER/D8PLAY01.SCN"
//       one scenario -> stdout
//
// A scenario is a set of files sharing a base name: .SCN (text: names, day/night, teams, objects),
// .MAP (binary tile grid), .MTG (binary trigger-id grid), .PTH (binary path families and routing
// matrix), .TRO (text trigger script), .POP (text, map editor's vent eruption data, not read by
// the game) and the overview-image caches .OVH/.O16 (regenerated by the game, exported only with
// --images). The formats and the addresses of the game's loaders are documented in
// docs/DC16_MAP_FILES.md; that document is the reference for every field written here.
//
// Coordinates: the JSON uses the game's own tile coordinates (x, z). All grids are indexed
// [z][x] with z = 0 at the LAST row of the .MAP/.MTG file (the game flips those two files on
// load; .PTH, .SCN, .TRO and .POP are already in game order). Row r of the file is z = height-1-r.

